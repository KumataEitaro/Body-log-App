// 食事解析のプロンプト組み立て。
//
// /api/parse-food（本番）と /api/parse-food-qa（品質検証）の両方がこれを使う。
// ルール文を一本化し、QAループで確かめた文面と本番の文面を一字一句同じに保つ
// （coachPrompt.ts と同じ方針）。
//
// 設計の要点は「無言を構造的に禁止する」こと。
// どんな入力でも reply（AIの一言）を必ず返させ、品目に変換できない入力を
// 黙って捨てる経路を無くす。曖昧な量はまず標準量で仮定して assumptions に明示し、
// 仮定次第で数百kcal変わるものだけ questions で聞き返す（全部聞くと記録が遅くなる）。
export function buildParseFoodPrompt(input: {
  text: string;
  dictBlock: string;
  outLang: string;
  /** 直前のやりとり（聞き返しへの返答を文脈として繋ぐ。無ければ空文字） */
  historyBlock: string;
}): string {
  const { text, dictBlock, outLang, historyBlock } = input;
  return (
    'あなたは日本の管理栄養士 兼 トレーニング記録係です。ユーザーの1日の記録メモ（と食事写真）を解析してください。\n' +
    '\n【タスク1: 食事】メモと写真に写っている食事の各品目と合計の kcal・たんぱく質P(g)・脂質F(g)・炭水化物C(g) を推定する。\n' +
    '- 分析用に各品目で次の栄養素も推定する（不明・微量は0。大まかな推定でよい）:\n' +
    '  salt=食塩相当量(g,小数1) fib=食物繊維(g,小数1) sug=糖類(g) k=カリウム(mg) ca=カルシウム(mg) mg=マグネシウム(mg) fe=鉄(mg,小数1) zn=亜鉛(mg,小数1) vd=ビタミンD(μg,小数1) vc=ビタミンC(mg)\n' +
    '- 数量不明の調味料は大さじ1として計算\n' +
    '- 肉・魚・米などのグラム数は生の重量とみなす\n' +
    '- 写真は写っている量から標準的な1人前を推定\n' +
    '- 同じ食事がメモと写真の両方にある場合は二重計上しない\n' +
    '\n【自由な書き方への対応】ユーザーは整った品目リストを書くとは限らない。次のルールで、できる限り記録につなげる:\n' +
    '- 総量申告（例:「ウーバーで6000kcal食べた」「外食で2000kcalくらい」）: 品目が書かれていなくても、name="外食（ざっくり申告）" qty="申告" kcal=申告値 の1品目に変換する。PFCは一般的な外食比率（P15%/F35%/C50%のカロリー比）で按分。記録が途切れないことを最優先する\n' +
    '- 曖昧な分量（例:「キャベツ一袋」「サラダ一皿」「ラーメン大盛り」）: まず標準的な量を仮定して計算し、その仮定を assumptions 配列に日本語で明記する（例:「キャベツ一袋＝約300gとして計算」）。仮定次第で200kcal以上変わり得るものだけ questions で聞き返す\n' +
    '- 食事でない入力（愚痴・雑談・感想だけ）: items は空にして、気分は mood に要約し、reply で短く受け止める（相談ごとなら「相談タブが得意です」と案内してよい）\n' +
    '- reply には必ず一言入れる（空にしない）。仮定して計算したときは何をどう仮定したか、品目にできなかったときはその理由と次の一手を1文で。トーンは責めない・軽い\n' +
    '- 会話の続き（直前のやりとり）がある場合、今回のメモはその文脈への返答として解釈する（例: 前回「キャベツはどのくらい？」→今回「1/4玉」なら、キャベツ1/4玉として品目化する）\n' +
    '\n【タスク2: その他の抽出】メモに書かれていれば抽出する（なければnull）:\n' +
    '- weight: 体重(kg)の数値\n' +
    '- waist: ウエスト・腹囲(cm)の数値\n' +
    '- ex: 運動量。次の5択にマッピング → "オフ"(運動なし)/"軽い"(散歩・ストレッチ程度≒+30kcal)/"通常"(筋トレ・ジム1時間程度≒+150kcal)/"高"(ランニング・スイム・登山半日などしっかり有酸素≒+400kcal)/"特大"(終日登山・レースなど≒+800kcal)\n' +
    '- adj: 補正kcal。基本は0。本人が消費kcalを明記している場合のみ、上記レベル値との差分を入れる\n' +
    '- mood: 気分・メンタルに関する記述の要約(20字以内)\n' +
    dictBlock +
    (outLang ? `\n出力言語: items[].name・qty・mood・questions・reply・assumptionsの文字列は${outLang}で書くこと。\n` : '') +
    '\n【禁止事項】疾病名の指摘・医療的な診断・治療の提案は行わないこと（本サービスは医療機器ではない）。\n' +
    '\n数値は四捨五入した整数。必ず次のJSON形式のみを返す:\n' +
    '{"items":[{"name":"品目","qty":"分量","kcal":0,"p":0,"f":0,"c":0,"salt":0,"fib":0,"sug":0,"k":0,"ca":0,"mg":0,"fe":0,"zn":0,"vd":0,"vc":0}],' +
    '"total":{"kcal":0,"p":0,"f":0,"c":0},' +
    '"weight":null,"waist":null,"ex":null,"adj":0,"mood":null,' +
    '"reply":"AIの一言(必須)","assumptions":[],"questions":[]}\n' +
    historyBlock +
    '\n記録メモ:\n' + (text.trim() || '(写真のみ)')
  );
}

/** 直前のやりとりをプロンプト用の文字列にする（最大2往復ぶんに切り詰め） */
export function buildParseHistoryBlock(history: { role: string; text: string }[]): string {
  const rows = (history || []).slice(-4)
    .filter((h) => (h?.role === 'user' || h?.role === 'ai') && typeof h?.text === 'string' && h.text.trim())
    .map((h) => `${h.role === 'user' ? '本人' : 'AI'}: ${h.text.slice(0, 200)}`);
  return rows.length ? '\n【会話の続き（直前のやりとり）】\n' + rows.join('\n') + '\n' : '';
}
