// 日付跨ぎ（JST 0時）で表示日が「昨日」に取り残されないことの固定。
// タブは常駐するため、夜に開いたまま翌朝戻ると朝食が昨日の12:00として保存される事故があった。
import { rolloverDate } from '../rollover';

describe('rolloverDate（表示日の今日追従）', () => {
  it('「今日」を見ていた人は、日付が変わったら新しい今日へ移る', () => {
    expect(rolloverDate('2026-09-01', '2026-09-01', '2026-09-02')).toBe('2026-09-02');
  });
  it('過去日をわざわざ見ていた人の表示日は動かさない', () => {
    expect(rolloverDate('2026-08-28', '2026-09-01', '2026-09-02')).toBe('2026-08-28');
  });
  it('日付が変わっていなければ何もしない', () => {
    expect(rolloverDate('2026-09-01', '2026-09-01', '2026-09-01')).toBe('2026-09-01');
    expect(rolloverDate('2026-08-28', '2026-09-01', '2026-09-01')).toBe('2026-08-28');
  });
  it('2日以上放置しても（9/1→9/3）新しい今日へ一気に移る', () => {
    expect(rolloverDate('2026-09-01', '2026-09-01', '2026-09-03')).toBe('2026-09-03');
  });
});
