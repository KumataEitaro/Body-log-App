/** ウェルカム画面に出す少数の例（毎回同じ4つでは飽きるので日替わりにする） */
export function featuredQuestions(dayIndex: number, n = 4): string[] {
  const all = askCategories().flatMap((c) => c.questions);
  if (all.length === 0) return [];
  const out: string[] = [];
  for (let i = 0; i < n; i++) {
    out.push(all[(dayIndex * n + i) % all.length]);
  }
  return out;
}
