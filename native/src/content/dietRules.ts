// 食事の制約（B-18）のプリセット辞書。docs/DIET-MODES.md §1 の「1つの器」の中身。
//
// ここは**警告の判定基準**であり、AI相談用の好み（profiles.constraints_note）とは役割が違う。
// 端末内に生値で持つので、オフラインでも無料プランでも最低限の警告が出る（§2の二段構えの①）。
//
// ===== 黒(high)と灰(maybe)を分ける理由 =====
// high = その語が出た時点で対象を含む可能性が高いもの（豚肉・小麦粉など）。
// maybe = 製品・店・調理法によって変わるもの（しょうゆ・みそ・カレールー・パンなど）。
// 日本の調味料はグルテンフリーではほぼ全てが灰になる（小麦を使う醸造が主流だが、
// 「小麦不使用」表示の製品も普通に流通しているため断定できない）。
// 灰を黒に混ぜると警告が鳴りっぱなしになり、本当に見るべき黒が埋もれる＝安全性が下がる。
//
// ===== 語の選び方（誤検知を作らないための規約） =====
// 判定は「正規化した文字列に語が含まれるか」の部分一致。仮名はカタカナに畳むため、
// **2文字の仮名語は他語の一部に埋もれやすい**（スイカ⊃イカ／タコス⊃タコ／ラムネ⊃ラム／
// ブリトー⊃ブリ／アジア⊃アジ／ぶどうにんじん⊃ウニ）。
// そのため2文字の仮名は誤検知の実例が思いつかないものだけに絞り、
// 残りは漢字表記（烏賊・蛸・鯵）や3文字以上の語（イカリング・たこ焼き）で拾う。
// 同じ理由で1文字の漢字も避ける（乳⊂豆乳／肉⊂果肉／牛⊂牛蒡）。
// 見落としは仕様上あり得る前提で、UIには常設の免責を必ず併記すること（§6-4）。
//
// 英語の語はASCII単語境界で判定する（ham が graham に当たらないように）。

/** プリセットのキー。DBの profiles.diet_modes にはこの文字列配列が入る */
export type DietModeKey = 'vegan' | 'vegetarian' | 'gluten_free' | 'halal' | 'dairy_free';

/** 警告の強さ。none は「該当なし」＝配列に入れないことで表す（安全の保証ではない・§6） */
export type DietLevel = 'high' | 'maybe';

export type DietRule = {
  key: DietModeKey;
  /** 設定画面の行タイトル（t()の原文キーとして使う） */
  label: string;
  /** 行の補足（t()の原文キー） */
  sub: string;
  /** 黒: 対象を含む可能性が高い語 */
  high: string[];
  /** 灰: 製品・調理によって含む語 */
  maybe: string[];
};

