/** プリセット一覧（設定画面の表示順） */
export const DIET_RULES: DietRule[] = [VEGAN, VEGETARIAN, GLUTEN_FREE, HALAL, DAIRY_FREE];

/** キーからルールを引く（未知のキーはundefined＝無視される） */
export function ruleOf(key: string): DietRule | undefined {
  return DIET_RULES.find((r) => r.key === key);
}

/** 有効なキー配列 → ルール配列（不正値・重複を落とす） */
export function rulesFor(keys: readonly string[] | null | undefined): DietRule[] {
  if (!Array.isArray(keys)) return [];
  const seen = new Set<string>();
  const out: DietRule[] = [];
  for (const k of keys) {
    if (typeof k !== 'string' || seen.has(k)) continue;
    seen.add(k);
    const r = ruleOf(k);
    if (r) out.push(r);
  }
  return out;
}
